from config.settings import settings


class PowerGridSensorGenerator:
    """
    Simulates high-fidelity multi-station electrical grid sensor telemetry.
    Generates realistic AC power parameters under normal and abnormal fault conditions.
    """

    FEEDERS = ["FEEDER-A", "FEEDER-B", "FEEDER-C"]

    # Fault conditions mapping
    FAULT_CONDITIONS = [
        "Normal",
        "Overload",
        "Short Circuit",
        "Voltage Sag",
        "Voltage Swell",
        "Frequency Anomaly",
        "Overheating"
    ]

    def __init__(self, random_seed: Optional[int] = 42):
        if random_seed is not None:
            random.seed(random_seed)
            np.random.seed(random_seed)
        self.stations = settings.GRID_STATIONS

    def _generate_sensor_id(self, station_id: str, feeder_id: str, index: int) -> str:
        """Constructs standardized sensor identifier."""
        return f"SNS-{station_id}-{feeder_id[-1]}-{index:02d}"

    def generate_single_reading(
        self,
        station_id: Optional[str] = None,
        feeder_id: Optional[str] = None,
        sensor_index: int = 1,
        condition: Optional[str] = None,
        timestamp: Optional[datetime] = None
    ) -> Dict[str, Any]:
        """
        Generates a single synthetic sensor reading based on the requested condition.
        Calculates physically consistent active power, reactive power, and power factor.
        """
        if timestamp is None:
            timestamp = datetime.utcnow()

        if station_id is None:
            st = random.choice(self.stations)
            station_id = st["station_id"]
            nominal_kv = st["nominal_kv"]
        else:
            st = next((s for s in self.stations if s["station_id"] == station_id), self.stations[0])
            nominal_kv = st["nominal_kv"]

        if feeder_id is None:
            feeder_id = random.choice(self.FEEDERS)

        sensor_id = self._generate_sensor_id(station_id, feeder_id, sensor_index)

        # Select condition randomly if not specified
        if condition is None:
            # 70% normal, 30% faulty by default in general distribution
            if random.random() < 0.70:
                condition = "Normal"
            else:
                condition = random.choice(self.FAULT_CONDITIONS[1:])

        # Base nominal parameters
        v_nom = nominal_kv  # e.g. 11.0 kV
        f_nom = settings.NOMINAL_FREQUENCY_HZ  # 50.0 Hz

        # Physics simulation per operating condition
        if condition == "Normal":
            # Normal distribution around rated values
            voltage = float(np.random.normal(v_nom, 0.12))  # ~ 10.7 - 11.3 kV
            voltage = np.clip(voltage, v_nom * 0.95, v_nom * 1.05)
            current = float(np.random.normal(180.0, 35.0))  # 110 - 250 A
            current = np.clip(current, 80.0, 280.0)
            frequency = float(np.random.normal(f_nom, 0.04))  # 49.88 - 50.12 Hz
            power_factor = float(np.random.uniform(0.92, 0.98))
            temperature = float(np.random.normal(45.0, 4.0))  # 37 - 53 °C
            load_pct = (current / 300.0) * 100.0
            breaker_status = "CLOSED"

        elif condition == "Overload":
            # Elevated current exceeding rated thermal line limits
            voltage = float(np.random.normal(v_nom * 0.94, 0.15))  # slight voltage drop
            current = float(np.random.uniform(380.0, 600.0))  # above rated 300A
            frequency = float(np.random.normal(f_nom - 0.15, 0.08))
            power_factor = float(np.random.uniform(0.82, 0.89))  # inductive drop
            temperature = float(np.random.uniform(68.0, 92.0))  # elevated heat
            load_pct = (current / 300.0) * 100.0  # 125% - 200%
            breaker_status = "CLOSED" if random.random() < 0.85 else "TRIPPED"

        elif condition == "Short Circuit":
            # Massive current surge, voltage collapse, immediate breaker trip
            voltage = float(np.random.uniform(1.5, 4.8))  # severe voltage drop
            current = float(np.random.uniform(1200.0, 2800.0))  # massive fault current
            frequency = float(np.random.normal(f_nom - 0.45, 0.20))
            power_factor = float(np.random.uniform(0.20, 0.45))  # highly reactive inductive
            temperature = float(np.random.uniform(75.0, 115.0))
            load_pct = min(350.0, (current / 300.0) * 100.0)
            breaker_status = "TRIPPED"

        elif condition == "Voltage Sag":
            # Dip between 10% and 90% nominal voltage (0.5 to 0.85 pu)
            sag_pu = float(np.random.uniform(0.55, 0.84))
            voltage = v_nom * sag_pu
            current = float(np.random.normal(210.0, 40.0))
            frequency = float(np.random.normal(f_nom, 0.06))
            power_factor = float(np.random.uniform(0.85, 0.94))
            temperature = float(np.random.normal(46.0, 5.0))
            load_pct = (current / 300.0) * 100.0
            breaker_status = "CLOSED"

        elif condition == "Voltage Swell":
            # Momentary voltage elevation (1.15 to 1.45 pu)
            swell_pu = float(np.random.uniform(1.15, 1.45))
            voltage = v_nom * swell_pu
            current = float(np.random.normal(160.0, 30.0))
            frequency = float(np.random.normal(f_nom, 0.06))
            power_factor = float(np.random.uniform(0.90, 0.96))
            temperature = float(np.random.normal(48.0, 5.0))
            load_pct = (current / 300.0) * 100.0
            breaker_status = "CLOSED"

        elif condition == "Frequency Anomaly":
            # Grid instability exceeding ±0.8 Hz statutory limit
            voltage = float(np.random.normal(v_nom, 0.18))
            current = float(np.random.normal(190.0, 40.0))
            # Either frequency plunge (<49.1 Hz) or surge (>51.0 Hz)
            if random.random() < 0.5:
                frequency = float(np.random.uniform(47.2, 49.0))
            else:
                frequency = float(np.random.uniform(51.1, 52.8))
            power_factor = float(np.random.uniform(0.88, 0.95))
            temperature = float(np.random.normal(47.0, 4.0))
            load_pct = (current / 300.0) * 100.0
            breaker_status = "CLOSED"

        elif condition == "Overheating":
            # Thermal failure, cooling pump fault, bushing breakdown
            voltage = float(np.random.normal(v_nom, 0.10))
            current = float(np.random.normal(230.0, 30.0))
            frequency = float(np.random.normal(f_nom, 0.03))
            power_factor = float(np.random.uniform(0.91, 0.96))
            temperature = float(np.random.uniform(92.0, 135.0))  # Dangerous thermal surge
            load_pct = (current / 300.0) * 100.0
            breaker_status = "CLOSED" if temperature < 115.0 else "TRIPPED"

        else:
            # Fallback
            condition = "Normal"
            voltage = v_nom
            current = 180.0
            frequency = f_nom
            power_factor = 0.95
            temperature = 45.0
            load_pct = 60.0
            breaker_status = "CLOSED"

        # Three-Phase AC Power Computations:
        # P (kW) = sqrt(3) * V(kV) * I(A) * cos(theta)
        # Q (kVAR) = sqrt(3) * V(kV) * I(A) * sin(theta)
        sin_theta = math.sqrt(max(0.0, 1.0 - power_factor ** 2))
        active_power = math.sqrt(3.0) * voltage * current * power_factor
        reactive_power = math.sqrt(3.0) * voltage * current * sin_theta

        # Small physical noise
        active_power += float(np.random.normal(0, active_power * 0.01))
        reactive_power += float(np.random.normal(0, reactive_power * 0.01))

        return {
            "sensor_id": sensor_id,
            "timestamp": timestamp.isoformat(),
            "station_id": station_id,
            "feeder_id": feeder_id,
            "voltage_kv": round(float(voltage), 3),
            "current_a": round(float(current), 2),
            "frequency_hz": round(float(frequency), 3),
            "active_power_kw": round(float(active_power), 2),
            "reactive_power_kvar": round(float(reactive_power), 2),
            "power_factor": round(float(power_factor), 3),
            "temperature_c": round(float(temperature), 2),
            "load_pct": round(float(load_pct), 2),
            "breaker_status": breaker_status,
            "target_condition": condition,
            "is_valid": True,
            "simulation_tag": "SYNTHETIC_RESEARCH_DATA"
        }

    def generate_dataset(
        self,
        n_samples: int = 7000,
        start_time: Optional[datetime] = None,
        time_step_sec: int = 5
    ) -> pd.DataFrame:
        """
        Generates a balanced time-series synthetic dataset covering all 7 operating conditions.
        Saves raw dataset and sample dataset.
        """
        if start_time is None:
            start_time = datetime.utcnow() - timedelta(seconds=n_samples * time_step_sec)

        records = []
        samples_per_condition = n_samples // len(self.FAULT_CONDITIONS)
        remainder = n_samples % len(self.FAULT_CONDITIONS)

        current_time = start_time

        print(f"Generating {n_samples} synthetic power-grid telemetry records...")
        for cond_idx, condition in enumerate(self.FAULT_CONDITIONS):
            count = samples_per_condition + (remainder if cond_idx == 0 else 0)
            for _ in range(count):
                st = random.choice(self.stations)
                feeder = random.choice(self.FEEDERS)
                sensor_idx = random.randint(1, 4)

                reading = self.generate_single_reading(
                    station_id=st["station_id"],
                    feeder_id=feeder,
                    sensor_index=sensor_idx,
                    condition=condition,
                    timestamp=current_time
                )
                records.append(reading)
                current_time += timedelta(seconds=time_step_sec)

        df = pd.DataFrame(records)
        # Shuffle records to avoid contiguous condition blocks
        df = df.sample(frac=1.0, random_state=42).reset_index(drop=True)

        # Inject realistic minor data hygiene flaws to test preprocessing (0.5% missing, 0.2% minor outliers)
        n_flawed = int(len(df) * 0.005)
        flaw_indices = np.random.choice(len(df), n_flawed, replace=False)
        for idx in flaw_indices[:n_flawed // 2]:
            # Missing sensor reading
            df.loc[idx, "reactive_power_kvar"] = np.nan
        for idx in flaw_indices[n_flawed // 2:]:
            # Minor sensor noise spike
            df.loc[idx, "temperature_c"] = 185.0

        print(f"Generated {len(df)} records across {len(self.FAULT_CONDITIONS)} conditions.")
        return df


def main():
    """Generates raw and sample datasets and saves to disk."""
    generator = PowerGridSensorGenerator()
    
    # Generate 7,000 samples for robust ML training & evaluation
    df = generator.generate_dataset(n_samples=7000)

    raw_path = settings.RAW_DATA_DIR / "power_grid_telemetry_raw.csv"
    sample_path = settings.SAMPLE_DATA_DIR / "power_grid_sample.csv"

    df.to_csv(raw_path, index=False)
    print(f"Saved raw dataset: {raw_path}")

    # Save a 500-row sample for quick unit testing and inspections
    df.head(500).to_csv(sample_path, index=False)
    print(f"Saved sample dataset: {sample_path}")

    print("\nDataset Summary by Target Condition:")
    print(df["target_condition"].value_counts())


if __name__ == "__main__":
    main()
